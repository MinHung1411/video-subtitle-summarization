"""
Exporter Module:
Generates formatted Markdown reports and downloadable files.
"""

import os
import tempfile
import uuid
from typing import List, Dict

def format_markdown_report(
    title: str,
    executive_summary: str,
    chapters: List[Dict],
    keywords: str,
    metadata: Dict,
) -> str:
    md = []
    md.append(f"# Summary Report: {title}\n")
    md.append(f"> Duration: {metadata.get('duration_str', 'N/A')} | "
              f"Language: {metadata.get('language', 'N/A').upper()} | "
              f"Word Count: {metadata.get('word_count', 0):,}\n")
    md.append("---\n")

    md.append("## 1. Executive Summary\n")
    md.append(f"{executive_summary}\n\n")

    md.append("## 2. Key Concepts\n")
    md.append(f"`{keywords}`\n\n")

    if chapters and len(chapters) > 1:
        md.append("## 3. Chapter Timeline\n")
        for ch in chapters:
            time_str = ch.get("time_str", "")
            summary = ch.get("summary", "")
            md.append(f"### [{time_str}] Chapter {ch.get('chunk_id')}")
            md.append(f"- {summary}\n")

    md.append("\n---\n*Generated by Video Subtitle Understanding & Summarization Pipeline.*")
    return "\n".join(md)

def create_downloadable_file(markdown_content: str, filename_prefix: str = "video_summary") -> str:
    temp_dir = tempfile.gettempdir()
    file_id = uuid.uuid4().hex[:6]
    filepath = os.path.join(temp_dir, f"{filename_prefix}_{file_id}.md")
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(markdown_content)
    return filepath
